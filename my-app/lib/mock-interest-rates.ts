const months = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"];

function buildSeries(values: number[]): DataPoint[] {
  return values.map((value, i) => ({
    date: `${months[i % 12]} ${2020 + Math.floor(i / 12)}`,
    value,
  }));
}

